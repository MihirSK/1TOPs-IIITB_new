module tb_clint_full;
  bit d1, d4;
  int e1, e4, o1, o4;
  int tot_e, tot_o;

  tb_clint_core #(.HARTS(1), .TAG("H1")) u1 (.done(d1), .nerr(e1), .nopen(o1));
  tb_clint_core #(.HARTS(4), .TAG("H4")) u4 (.done(d4), .nerr(e4), .nopen(o4));

  initial begin
    wait (d1 && d4);
    #100;
    tot_e = e1 + e4; tot_o = o1 + o4;
    $display("==================================================");
    $display(" contract errors = %0d (H1 %0d, H4 %0d)   open-item hits = %0d  (bus handshake: req held until ack)", tot_e, e1, e4, tot_o);
    if (tot_e != 0)      $display(" *** RESULT: FAIL ***");
    else if (tot_o != 0) $display(" *** RESULT: PASS WITH OPEN ITEMS (%0d) - not signed off ***", tot_o);
    else                 $display(" *** RESULT: PASS ***");
    $display("==================================================");
    $finish;
  end

  initial begin
    #500_000_000;
    $display("GLOBAL WATCHDOG TIMEOUT");
    $display(" *** RESULT: FAIL ***");
    $finish;
  end
endmodule
