// ============================================================================
//  tb_clint_full.sv  -  Functional verification testbench for clint.sv
//  Plain SystemVerilog (no covergroups/SVA, no dut.* references), xsim/Verilator.
//
//  Top module tb_clint_full runs two instances of the same testbench at once:
//      HARTS = 1  (the SoC configuration)   and   HARTS = 4  (odd/even lanes, ranges)
//  Reference model (independent of the RTL): mtime, mtimecmp[h], msip[h],
//  updated at every clock edge from the bus inputs and rtc_tick. Every cycle:
//    * msip[h] / mtip[h] pins == model (mtip = unsigned mtime >= mtimecmp)
//    * an accepted request is answered with ack one cycle later, never otherwise
//    * read data == model (msip: the addressed 32-bit lane; 64-bit registers: all
//      64 bits; unmapped: 0, never stale data)
//  Bus convention (as generated by riscv_core): a 32-bit store drives {2{data}}
//  with strb = 0x0F << (4*addr[2]); a load takes the lane selected by addr[2].
//  Masters: PULSE (req for one edge, contract) and HOLD (req held until ack is
//  seen, O1, reported as OPEN ITEM).
//
//  Result lines:  RESULT: PASS | PASS WITH OPEN ITEMS (n) | FAIL
//  -define STRICT_OPEN makes open items fail.
// ============================================================================
`timescale 1ns/1ps

module tb_clint_core #(
    parameter int    HARTS = 1,
    parameter string TAG   = "H1"
)(
    output bit done,
    output int nerr,
    output int nopen
);

  localparam logic [63:0] BASE = 64'h0000_0000_0200_0000;

  logic        clk   = 1'b0;
  logic        rst_n = 1'b0;
  always #5 clk = ~clk;

  logic        rtc_tick = 1'b0;
  logic [63:0] addr  = '0;
  logic [63:0] wdata = '0;
  logic [7:0]  strb  = '0;
  logic        req   = 1'b0;
  logic        we    = 1'b0;
  logic [63:0] rdata;
  logic        ack;
  logic [HARTS-1:0] msip;
  logic [HARTS-1:0] mtip;

  clint #(.HARTS(HARTS)) dut (.*);

  // --------------------------------------------------------------------------
  bit open_mode = 1'b0;
  function automatic void err(input string m);
    if (open_mode) begin
`ifdef STRICT_OPEN
      nerr++;
      if (nerr <= 40) $display("[%0t] %s ERROR (open item, strict): %s", $time, TAG, m);
`else
      nopen++;
      if (nopen <= 8) $display("[%0t] %s OPEN-ITEM: %s", $time, TAG, m);
`endif
    end else begin
      nerr++;
      if (nerr <= 40) $display("[%0t] %s ERROR: %s", $time, TAG, m);
    end
  endfunction

  bit armed = 1'b0;

  // coverage counters (a hole fails the run)
  int cov_msip_set  [8];
  int cov_msip_clr  [8];
  int cov_cmp_w     [8];
  int cov_cmp_r     [8];
  int cov_lane      [8];       // byte lane strobed alone on a 64-bit register
  int cov_rw        [4][2];    // kind {none,msip,cmp,mtime} x {read,write}
  int cov_ev        [16];

  // --------------------------------------------------------------------------
  // Reference model + checker (samples at every posedge, before the DUT updates)
  // --------------------------------------------------------------------------
  logic [63:0] m_mtime = '0;
  logic [63:0] m_cmp  [HARTS];
  bit          m_msip [HARTS];
  bit          pend = 1'b0, pend_rd = 1'b0;
  int          pend_kind = 0, pend_lane = 0;
  logic [63:0] pend_exp = '0;
  int          hh, kind;
  bit          acc_m, wr_mt, sst, sdv;
  logic        lane_m;

  function automatic logic [63:0] merge64(input logic [63:0] old, input logic [63:0] nw, input logic [7:0] st);
    logic [63:0] r;
    r = old;
    for (int b = 0; b < 8; b++) if (st[b]) r[b*8 +: 8] = nw[b*8 +: 8];
    return r;
  endfunction

  // hart index of an address (msip / mtimecmp region), 0 elsewhere
  function automatic int dec_h(input logic [63:0] a);
    logic [15:0] o;
    o = a[15:0];
    if (o < 16'h4000)      return int'(o[13:2]);
    else if (o < 16'hBFF8) return int'((o - 16'h4000) >> 3);
    else                   return 0;
  endfunction

  // 0 unmapped, 1 msip, 2 mtimecmp, 3 mtime
  function automatic int dec(input logic [63:0] a);
    logic [15:0] o;
    o = a[15:0];
    if (o < 16'h4000)      return (dec_h(a) < HARTS) ? 1 : 0;
    else if (o < 16'hBFF8) return (dec_h(a) < HARTS) ? 2 : 0;
    else if (o < 16'hC000) return 3;
    else                   return 0;
  endfunction

  always @(posedge clk) begin
    if (!rst_n) begin
      m_mtime = '0;
      for (int h = 0; h < HARTS; h++) begin m_cmp[h] = '1; m_msip[h] = 1'b0; end
      pend = 1'b0;
      if (armed && ack !== 1'b0) err("ack asserted while in reset");
    end else if (armed) begin
      for (int h = 0; h < HARTS; h++) begin
        if ($isunknown(mtip[h]) || $isunknown(msip[h])) err("X/Z on mtip/msip");
        else begin
          if (mtip[h] !== (m_mtime >= m_cmp[h]))
            err($sformatf("mtip[%0d]=%b, model mtime=%h mtimecmp=%h", h, mtip[h], m_mtime, m_cmp[h]));
          if (msip[h] !== m_msip[h]) err($sformatf("msip[%0d]=%b, model %b", h, msip[h], m_msip[h]));
        end
      end
      if ($isunknown(ack)) err("X/Z on ack");
      if (pend) begin
        if (ack !== 1'b1) err("no ack one cycle after an accepted request");
        else if (pend_rd) begin
          if (pend_kind == 1) begin
            if (rdata[32 * pend_lane +: 32] !== pend_exp[31:0])
              err($sformatf("msip read lane %0d = %h, expected %h", pend_lane, rdata[32 * pend_lane +: 32], pend_exp[31:0]));
          end else if (rdata !== pend_exp)
            err($sformatf("read data %h, expected %h (kind %0d)", rdata, pend_exp, pend_kind));
        end
      end else if (ack === 1'b1) err("ack without an accepted request (or ack held for two cycles)");

      // apply this clock edge to the model
      acc_m  = (req === 1'b1) && (ack !== 1'b1);
      pend   = acc_m; pend_rd = 1'b0; wr_mt = 1'b0;
      if (acc_m) begin
        hh = dec_h(addr); kind = dec(addr);
        pend_kind = kind; pend_lane = int'(addr[2]);
        cov_rw[kind][we ? 1 : 0]++;
        case (kind)
          1: begin
            pend_exp = {32'h0, 31'h0, m_msip[hh]}; pend_rd = !we;
            if (we) begin
              lane_m = addr[2]; sst = strb[4 * int'(lane_m)]; sdv = wdata[32 * int'(lane_m)];
              if (sst) begin
                m_msip[hh] = sdv;
                if (sdv) cov_msip_set[hh]++; else cov_msip_clr[hh]++;
              end
            end
          end
          2: begin
            pend_exp = m_cmp[hh]; pend_rd = !we;
            if (we) begin
              m_cmp[hh] = merge64(m_cmp[hh], wdata, strb);
              cov_cmp_w[hh]++;
            end else cov_cmp_r[hh]++;
          end
          3: begin
            pend_exp = m_mtime; pend_rd = !we;
            if (we) begin m_mtime = merge64(m_mtime, wdata, strb); wr_mt = 1'b1; end
          end
          default: begin pend_exp = 64'h0; pend_rd = !we; end
        endcase
        if (we && (kind == 2 || kind == 3))
          for (int b = 0; b < 8; b++) if (strb == (8'h01 << b)) cov_lane[b]++;
        if (we && kind == 3 && rtc_tick) cov_ev[0]++;          // write coincident with a tick
        if (!we && kind == 0) cov_ev[1]++;                      // unmapped read
      end
      if (rtc_tick && !wr_mt) m_mtime = m_mtime + 64'h1;
    end
  end

  // --------------------------------------------------------------------------
  // Drivers (act at negedge). rtc_tick is set only by set_tick().
  // --------------------------------------------------------------------------
  int  tick_mode = 0;          // 0 none, 1 every cycle, 2 random 1/tick_rate
  int  tick_rate = 4;
  bit  hold_mode = 1'b0;

  task automatic set_tick(input bit ftk);
    case (tick_mode)
      0:       rtc_tick = ftk;
      1:       rtc_tick = 1'b1;
      default: rtc_tick = ftk | ($urandom_range(0, tick_rate - 1) == 0);
    endcase
  endtask

  task automatic bus_op(input logic [63:0] a, input bit w, input logic [63:0] d, input logic [7:0] s,
                        input bit ftick, output logic [63:0] rd);
    addr = a; we = w; wdata = d; strb = s; req = 1'b1;
    set_tick(ftick);
    if (!hold_mode) begin
      @(negedge clk);                    // the accept edge has passed, ack/rdata are visible
      rd = rdata; req = 1'b0; set_tick(1'b0);
      @(negedge clk); set_tick(1'b0);
    end else begin
      @(negedge clk); set_tick(1'b0);
      @(posedge clk);                    // a synchronous master sees ack here
      rd = rdata;
      #1 req = 1'b0;
      @(negedge clk); set_tick(1'b0);
    end
  endtask

  task automatic idle(input int n);
    req = 1'b0;
    for (int i = 0; i < n; i++) begin set_tick(1'b0); @(negedge clk); end
  endtask

  // one tick pulse (mtime += 1) in its own cycle, tick_mode must be 0
  task automatic tick1();
    rtc_tick = 1'b1; @(negedge clk); rtc_tick = 1'b0;
  endtask

  task automatic banner(input string s);
    $display("[%0t] %s ---- %s", $time, TAG, s);
  endtask

  task automatic do_reset();
    req = 1'b0; rtc_tick = 1'b0; rst_n = 1'b0;
    repeat (3) @(negedge clk);
    armed = 1'b1;
    rst_n = 1'b1;
    @(negedge clk);
  endtask

  task automatic reset_async(input int cycles);
    #2 rst_n = 1'b0;
    repeat (cycles) @(negedge clk);
    rst_n = 1'b1;
    @(negedge clk);
  endtask

  // accessors (addresses are offsets from BASE)
  task automatic w64(input logic [15:0] o, input logic [63:0] d);
    logic [63:0] x;
    bus_op(BASE | 64'(o), 1'b1, d, 8'hFF, 1'b0, x);
  endtask
  task automatic wst(input logic [15:0] o, input logic [63:0] d, input logic [7:0] s);
    logic [63:0] x;
    bus_op(BASE | 64'(o), 1'b1, d, s, 1'b0, x);
  endtask
  task automatic w32(input logic [15:0] o, input logic [31:0] d);      // core convention: replicated data, lane strobe
    logic [63:0] x;
    bus_op(BASE | 64'(o), 1'b1, {d, d}, o[2] ? 8'hF0 : 8'h0F, 1'b0, x);
  endtask
  task automatic r64(input logic [15:0] o, output logic [63:0] v);
    bus_op(BASE | 64'(o), 1'b0, 64'h0, 8'h00, 1'b0, v);
  endtask
  task automatic r32(input logic [15:0] o, output logic [31:0] v);      // load: the addressed lane
    logic [63:0] x;
    bus_op(BASE | 64'(o), 1'b0, 64'h0, 8'h00, 1'b0, x);
    v = o[2] ? x[63:32] : x[31:0];
  endtask

  function automatic logic [15:0] o_msip(input int h); return 16'(4 * h); endfunction
  function automatic logic [15:0] o_cmp (input int h); return 16'(16'h4000 + 8 * h); endfunction
  localparam logic [15:0] O_MTIME = 16'hBFF8;

  function automatic logic [63:0] rnd64(); return {$urandom, $urandom}; endfunction

  // --------------------------------------------------------------------------
  // Tests
  // --------------------------------------------------------------------------
  task automatic test_reset_defaults();
    logic [63:0] v;
    logic [31:0] v32;
    banner("C1 reset defaults");
    do_reset();
    idle(4);
    if (msip !== '0) err("msip not 0 after reset");
    if (mtip !== '0) err("mtip not 0 after reset");
    r64(O_MTIME, v); if (v !== 64'h0) err($sformatf("mtime after reset = %h", v));
    for (int h = 0; h < HARTS; h++) begin
      r64(o_cmp(h), v); if (v !== '1) err($sformatf("mtimecmp[%0d] after reset = %h", h, v));
      r32(o_msip(h), v32); if (v32 !== 32'h0) err($sformatf("msip[%0d] read %h after reset", h, v32));
    end
    idle(20);
  endtask

  task automatic test_msip();
    logic [31:0] v32;
    banner("C2 msip: per hart set/clear, only bit 0, byte strobes, lanes, other harts untouched");
    for (int h = 0; h < HARTS; h++) begin
      logic [15:0] om;
      logic       ln;
      om = o_msip(h); ln = om[2];
      w32(o_msip(h), 32'h1);
      idle(1);
      if (msip[h] !== 1'b1) err($sformatf("msip[%0d] not set", h));
      for (int k = 0; k < HARTS; k++) if (k != h && msip[k] !== 1'b0) err($sformatf("msip[%0d] changed by a write to hart %0d", k, h));
      r32(o_msip(h), v32); if (v32 !== 32'h1) err($sformatf("msip[%0d] read %h, expected 1", h, v32));
      w32(o_msip(h), 32'hFFFF_FFFE);                         // bit 0 = 0 clears, other bits not stored
      if (msip[h] !== 1'b0) err($sformatf("msip[%0d] not cleared by data FFFFFFFE", h));
      w32(o_msip(h), 32'hFFFF_FFFF);
      r32(o_msip(h), v32); if (v32 !== 32'h1) err($sformatf("msip[%0d] read %h after writing FFFFFFFF, expected 1", h, v32));
      // byte strobes that do not include byte 0 of this register must not change it
      wst(o_msip(h), {2{32'h0000_0000}}, ln ? 8'hE0 : 8'h0E);
      if (msip[h] !== 1'b1) err($sformatf("msip[%0d] cleared by a write without byte 0 strobe", h));
      wst(o_msip(h), {2{32'h0000_0000}}, 8'h00);              // strb = 0: no effect
      if (msip[h] !== 1'b1) err($sformatf("msip[%0d] cleared by a write with strb=0", h));
      wst(o_msip(h), {2{32'h0000_0000}}, ln ? 8'h10 : 8'h01);   // byte 0 strobe alone clears
      if (msip[h] !== 1'b0) err($sformatf("msip[%0d] not cleared by a byte-0 write", h));
      // data only on the addressed lane, other lane zero / one
      wst(o_msip(h), ln ? {32'h1, 32'h0} : {32'h0, 32'h1}, ln ? 8'hF0 : 8'h0F);
      if (msip[h] !== 1'b1) err($sformatf("msip[%0d] not set with data only on its own lane", h));
      wst(o_msip(h), ln ? {32'h0, 32'h1} : {32'h1, 32'h0}, ln ? 8'hF0 : 8'h0F);   // '1' on the wrong lane only
      if (msip[h] !== 1'b0) err($sformatf("msip[%0d] set from the other lane's data", h));
      w32(o_msip(h), 32'h1); w32(o_msip(h), 32'h0);
    end
    // all harts set together, then clear one by one
    for (int h = 0; h < HARTS; h++) w32(o_msip(h), 32'h1);
    if (msip !== '1) err("not all msip bits set");
    for (int h = 0; h < HARTS; h++) begin w32(o_msip(h), 32'h0); end
    if (msip !== '0) err("msip not cleared");
    cov_ev[2]++;
  endtask

  task automatic test_mtimecmp();
    logic [63:0] v, pat [6];
    banner("C3 mtimecmp: 64-bit, byte strobes alone, 32-bit halves, every hart independent");
    pat[0] = 64'h0123_4567_89AB_CDEF; pat[1] = 64'hFFFF_FFFF_0000_0000; pat[2] = 64'h0000_0000_FFFF_FFFF;
    pat[3] = 64'h8000_0000_0000_0001; pat[4] = 64'hAAAA_5555_AAAA_5555; pat[5] = 64'h0000_0000_0000_0000;
    for (int h = 0; h < HARTS; h++) begin
      for (int i = 0; i < 6; i++) begin
        w64(o_cmp(h), pat[i]);
        r64(o_cmp(h), v); if (v !== pat[i]) err($sformatf("mtimecmp[%0d] read %h, wrote %h", h, v, pat[i]));
      end
      // each byte lane alone
      w64(o_cmp(h), 64'h0);
      for (int b = 0; b < 8; b++) begin
        wst(o_cmp(h), 64'hFFFF_FFFF_FFFF_FFFF, 8'h01 << b);
        wst(o_cmp(h), 64'h0, 8'hFF);
        wst(o_cmp(h), 64'hFFFF_FFFF_FFFF_FFFF, 8'h01 << b);
        r64(o_cmp(h), v); if (v !== (64'hFF << (8 * b))) err($sformatf("mtimecmp[%0d] byte %0d write: %h", h, b, v));
      end
      // 32-bit halves: low at +0, high at +4 (core convention)
      w64(o_cmp(h), 64'h0);
      w32(o_cmp(h),     32'h1122_3344);
      w32(o_cmp(h) + 4, 32'h5566_7788);
      r64(o_cmp(h), v); if (v !== 64'h5566_7788_1122_3344) err($sformatf("mtimecmp[%0d] halves: %h", h, v));
      begin
        logic [31:0] v32;
        r32(o_cmp(h),     v32); if (v32 !== 32'h1122_3344) err($sformatf("mtimecmp[%0d] low half read %h", h, v32));
        r32(o_cmp(h) + 4, v32); if (v32 !== 32'h5566_7788) err($sformatf("mtimecmp[%0d] high half read %h", h, v32));
      end
      w64(o_cmp(h), rnd64());
    end
    // independence: write distinct values, read all back
    for (int h = 0; h < HARTS; h++) w64(o_cmp(h), 64'hC0DE_0000_0000_0000 + 64'(h));
    for (int h = 0; h < HARTS; h++) begin
      r64(o_cmp(h), v); if (v !== 64'hC0DE_0000_0000_0000 + 64'(h)) err($sformatf("mtimecmp[%0d] overwritten by another hart: %h", h, v));
    end
    cov_ev[3]++;
  endtask

  task automatic test_mtime();
    logic [63:0] v;
    logic [31:0] v32;
    banner("C4 mtime: counting, byte/half writes, write vs tick, rollover");
    tick_mode = 0;
    w64(O_MTIME, 64'h0);
    for (int i = 0; i < 25; i++) begin tick1(); if ($urandom_range(0, 2) == 0) idle($urandom_range(1, 3)); end
    r64(O_MTIME, v); if (v !== 64'd25) err($sformatf("mtime = %0d after 25 ticks", v));
    // rtc_tick held for several cycles: one increment per cycle
    rtc_tick = 1'b1; repeat (7) @(negedge clk); rtc_tick = 1'b0;
    r64(O_MTIME, v); if (v !== 64'd32) err($sformatf("mtime = %0d after a 7-cycle tick, expected 32", v));
    // no tick, no change
    idle(30);
    r64(O_MTIME, v); if (v !== 64'd32) err($sformatf("mtime moved without ticks: %0d", v));
    // full write, halves, bytes
    w64(O_MTIME, 64'hFEDC_BA98_7654_3210);
    r64(O_MTIME, v); if (v !== 64'hFEDC_BA98_7654_3210) err($sformatf("mtime read %h after a 64-bit write", v));
    w32(O_MTIME,     32'hAAAA_0001);
    w32(O_MTIME + 4, 32'h0000_00BB);                                      // upper half at 0xBFFC
    r64(O_MTIME, v); if (v !== 64'h0000_00BB_AAAA_0001) err($sformatf("mtime halves: %h", v));
    r32(O_MTIME + 4, v32); if (v32 !== 32'h0000_00BB) err($sformatf("mtime upper half read %h", v32));
    for (int b = 0; b < 8; b++) begin
      w64(O_MTIME, 64'h0);
      wst(O_MTIME, 64'hFFFF_FFFF_FFFF_FFFF, 8'h01 << b);
      r64(O_MTIME, v); if (v !== (64'hFF << (8 * b))) err($sformatf("mtime byte %0d write: %h", b, v));
    end
    // a write coincident with a tick: the write wins, the tick is dropped
    w64(O_MTIME, 64'd100);
    begin
      logic [63:0] x;
      bus_op(BASE | 64'(O_MTIME), 1'b1, 64'd500, 8'hFF, 1'b1, x);        // rtc_tick in the same cycle
    end
    r64(O_MTIME, v); if (v !== 64'd500) err($sformatf("write coincident with a tick: mtime = %0d, expected 500", v));
    // tick one cycle before and one cycle after a write
    tick1(); w64(O_MTIME, 64'd700); tick1();
    r64(O_MTIME, v); if (v !== 64'd701) err($sformatf("tick around a write: mtime = %0d, expected 701", v));
    // read coincident with a tick returns the value before the increment
    begin
      logic [63:0] x, y;
      w64(O_MTIME, 64'd900);
      bus_op(BASE | 64'(O_MTIME), 1'b0, 64'h0, 8'h00, 1'b1, x);
      r64(O_MTIME, y);
      if (x !== 64'd900) err($sformatf("read coincident with a tick = %0d, expected 900", x));
      if (y !== 64'd901) err($sformatf("mtime after that tick = %0d, expected 901", y));
    end
    // rollover
    w64(O_MTIME, 64'hFFFF_FFFF_FFFF_FFFF);
    tick1();
    r64(O_MTIME, v); if (v !== 64'h0) err($sformatf("mtime after rollover = %h", v));
    tick_mode = 1; idle(10); tick_mode = 0;                                // running at one increment per cycle
    cov_ev[4]++;
  endtask

  task automatic test_mtip();
    logic [63:0] v;
    banner("C5 mtip: unsigned compare, edge cases, rises exactly when mtime reaches mtimecmp");
    tick_mode = 0;
    for (int h = 0; h < HARTS; h++) begin
      for (int k = 0; k < HARTS; k++) w64(o_cmp(k), 64'hFFFF_FFFF_FFFF_FFFF);   // park the other harts
      w64(O_MTIME, 64'd1000);
      w64(o_cmp(h), 64'd1003);
      idle(1);
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d] set early", h));
      tick1(); tick1();
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d] set at mtime=1002 < 1003", h));
      tick1();
      if (mtip[h] !== 1'b1) err($sformatf("mtip[%0d] not set at mtime == mtimecmp", h));
      for (int k = 0; k < HARTS; k++) if (k != h && mtip[k] !== 1'b0) err($sformatf("mtip[%0d] set by hart %0d's compare", k, h));
      tick1();
      if (mtip[h] !== 1'b1) err($sformatf("mtip[%0d] dropped at mtime > mtimecmp", h));
      w64(o_cmp(h), 64'd5000);                                             // moving the compare clears the interrupt
      idle(1);
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d] not cleared by a larger mtimecmp", h));
      w64(o_cmp(h), 64'd0);
      idle(1);
      if (mtip[h] !== 1'b1) err($sformatf("mtip[%0d] not set for mtimecmp = 0", h));
      // unsigned compare: bit 63 set
      w64(O_MTIME, 64'h7FFF_FFFF_FFFF_FFFF);
      w64(o_cmp(h), 64'h8000_0000_0000_0000);
      idle(1);
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d]: 7FFF.. >= 8000.. (signed compare?)", h));
      tick1();
      if (mtip[h] !== 1'b1) err($sformatf("mtip[%0d]: 8000.. >= 8000.. not seen", h));
      w64(O_MTIME, 64'hFFFF_FFFF_FFFF_FFFF);
      w64(o_cmp(h), 64'hFFFF_FFFF_FFFF_FFFF);
      idle(1);
      if (mtip[h] !== 1'b1) err($sformatf("mtip[%0d]: FFFF.. >= FFFF.. not seen", h));
      w64(o_cmp(h), 64'hFFFF_FFFF_FFFF_FFFF);
      w64(O_MTIME, 64'h0);
      idle(1);
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d] set with mtime=0, mtimecmp=FFFF..", h));
      // rollover makes mtip fall
      w64(O_MTIME, 64'hFFFF_FFFF_FFFF_FFFF); w64(o_cmp(h), 64'h0000_0000_0000_0005);
      tick1(); idle(1);
      if (mtip[h] !== 1'b0) err($sformatf("mtip[%0d] not cleared by rollover of mtime", h));
    end
    cov_ev[5]++;
  endtask

  task automatic test_unmapped();
    logic [63:0] v;
    logic [31:0] v32;
    logic [15:0] offs [12];
    banner("C6 unmapped/reserved addresses read 0 (never stale data) and ignore writes");
    offs[0] = o_msip(HARTS);            offs[1] = o_msip(HARTS + 3);  offs[2] = 16'h0FFC; offs[3] = 16'h2000;
    offs[4] = 16'h3FFC;                 offs[5] = o_cmp(HARTS);       offs[6] = o_cmp(HARTS + 5); offs[7] = 16'h5000;
    offs[8] = 16'hBFF0;                 offs[9] = 16'hC000;           offs[10] = 16'hFFF8;        offs[11] = 16'h8000;
    w32(o_msip(0), 32'h1);
    w64(o_cmp(0), 64'hDEAD_BEEF_0BAD_F00D);
    w64(O_MTIME, 64'h1234_5678_9ABC_DEF0);
    for (int i = 0; i < 12; i++) begin
      r64(o_cmp(0), v);                                  // makes stale data visible
      r64(offs[i], v);
      if (v !== 64'h0) err($sformatf("read of unmapped offset %h returned %h", offs[i], v));
      r32(o_msip(0), v32);
      r32(offs[i], v32);
      if (v32 !== 32'h0) err($sformatf("32-bit read of unmapped offset %h returned %h", offs[i], v32));
      w64(offs[i], 64'hFFFF_FFFF_FFFF_FFFF);       // must not change anything (monitor compares with the model)
    end
    idle(2);
    if (msip[0] !== 1'b1) err("msip changed by a write to an unmapped address");
    r64(o_cmp(0), v); if (v !== 64'hDEAD_BEEF_0BAD_F00D) err("mtimecmp changed by a write to an unmapped address");
    cov_ev[6]++;
  endtask

  task automatic test_reset_mid();
    logic [63:0] v;
    banner("C7 reset with state set and requests in flight");
    for (int h = 0; h < HARTS; h++) begin w32(o_msip(h), 32'h1); w64(o_cmp(h), 64'd10); end
    w64(O_MTIME, 64'd1234);
    for (int i = 0; i < 4; i++) begin
      addr = BASE | 64'(O_MTIME); we = 1'b1; wdata = 64'd77; strb = 8'hFF; req = 1'b1;
      #3 rst_n = 1'b0;                                      // asynchronous, mid-cycle, request in flight
      repeat (2 + i) @(negedge clk);
      req = 1'b0;
      rst_n = 1'b1;
      @(negedge clk);
      if (msip !== '0 || mtip !== '0) err("msip/mtip not cleared by reset");
      r64(O_MTIME, v); if (v !== 64'h0) err($sformatf("mtime after reset = %h", v));
      for (int h = 0; h < HARTS; h++) begin
        r64(o_cmp(h), v); if (v !== '1) err($sformatf("mtimecmp[%0d] after reset = %h", h, v));
        w32(o_msip(h), 32'h1); w64(o_cmp(h), 64'd10);
      end
      w64(O_MTIME, 64'd1234);
    end
    cov_ev[7]++;
  endtask

  function automatic logic [7:0] rnd_strb(input logic [15:0] o);
    case ($urandom_range(0, 5))
      0: return 8'hFF;
      1: return 8'h0F << (4 * int'(o[2]));
      2: return 8'h01 << $urandom_range(0, 7);
      3: return 8'($urandom);
      4: return 8'h00;
      default: return 8'hFF;
    endcase
  endfunction

  task automatic test_random(input int n);
    logic [63:0] v;
    logic [15:0] o;
    int r;
    banner("C8 constrained random over all regions, strobes, ticks, unmapped addresses");
    tick_mode = 2; tick_rate = 3;
    for (int i = 0; i < n; i++) begin
      if (i % 60 == 59) begin tick_mode = $urandom_range(0, 2); tick_rate = $urandom_range(2, 9); end
      r = $urandom_range(0, 99);
      case ($urandom_range(0, 5))
        0: o = o_msip($urandom_range(0, HARTS + 1));
        1: o = o_cmp($urandom_range(0, HARTS + 1)) + 16'($urandom_range(0, 1)) * 4;
        2: o = O_MTIME + 16'($urandom_range(0, 1)) * 4;
        3: o = 16'($urandom);
        4: o = o_cmp($urandom_range(0, HARTS - 1));
        default: o = o_msip($urandom_range(0, HARTS - 1));
      endcase
      if (r < 40) begin
        v = ($urandom_range(0, 3) == 0) ? 64'($urandom_range(0, 3)) : rnd64();
        if ($urandom_range(0, 9) == 0) v = (v & 64'h1) ? 64'hFFFF_FFFF_FFFF_FFFF : 64'h0;
        bus_op(BASE | 64'(o), 1'b1, v, rnd_strb(o), 1'($urandom_range(0, 3) == 0), v);
      end else if (r < 85) begin
        bus_op(BASE | 64'(o), 1'b0, 64'h0, 8'h00, 1'($urandom_range(0, 3) == 0), v);
      end else if (r < 92) begin
        idle($urandom_range(1, 6));
      end else if (r < 96) begin
        // put mtime close to mtimecmp so that mtip toggles
        v = rnd64();
        w64(O_MTIME, {v[63:8], 8'h00});
        v = rnd64();
        w64(o_cmp($urandom_range(0, HARTS - 1)), {v[63:8], 8'h08});
      end else begin
        w64(O_MTIME, ($urandom_range(0, 1) == 0) ? 64'hFFFF_FFFF_FFFF_FFF0 : 64'h7FFF_FFFF_FFFF_FFF0);
        tick_mode = 1; idle(20); tick_mode = 2;
      end
    end
    tick_mode = 0;
    idle(5);
  endtask

  // ------------------------------------------------------------------------
  // OPEN ITEM: a synchronous master that holds req until it sees ack.
  // ------------------------------------------------------------------------
  task automatic test_hold_open();
    logic [63:0] v;
    logic [31:0] v32;
    banner("O1 OPEN ITEM: master holds req until ack (ack must be one cycle wide)");
    do_reset();
    open_mode = 1'b1; hold_mode = 1'b1;
    for (int h = 0; h < HARTS; h++) begin
      w32(o_msip(h), 32'h1);
      r32(o_msip(h), v32); if (v32 !== 32'h1) err("HOLD: msip read");
      w64(o_cmp(h), 64'h1122_3344_5566_7788);
      r64(o_cmp(h), v); if (v !== 64'h1122_3344_5566_7788) err("HOLD: mtimecmp read");
      w32(o_msip(h), 32'h0);
    end
    w64(O_MTIME, 64'd42);
    r64(O_MTIME, v); if (v !== 64'd42) err("HOLD: mtime read");
    hold_mode = 1'b0;
    idle(4);
    open_mode = 1'b0;
    do_reset();
    cov_ev[8]++;
  endtask

  task automatic report_cov();
    for (int h = 0; h < HARTS; h++) begin
      if (cov_msip_set[h] == 0 || cov_msip_clr[h] == 0) err($sformatf("COVERAGE: msip[%0d] never both set and cleared", h));
      if (cov_cmp_w[h] == 0 || cov_cmp_r[h] == 0)       err($sformatf("COVERAGE: mtimecmp[%0d] never written and read", h));
    end
    for (int b = 0; b < 8; b++) if (cov_lane[b] == 0) err($sformatf("COVERAGE: byte lane %0d never written alone", b));
    for (int k = 1; k < 4; k++) for (int w = 0; w < 2; w++)
      if (cov_rw[k][w] == 0) err($sformatf("COVERAGE: region %0d %s never accessed", k, w ? "write" : "read"));
    if (cov_rw[0][0] == 0 || cov_rw[0][1] == 0) err("COVERAGE: unmapped read/write never accessed");
    if (cov_ev[0] == 0) err("COVERAGE: mtime write coincident with rtc_tick never hit");
    for (int i = 1; i < 9; i++) if (cov_ev[i] == 0) err($sformatf("COVERAGE: scenario %0d never ran", i));
    $display(" %s coverage: harts=%0d msip/mtimecmp per hart, 8 byte lanes, 3 regions + unmapped, write-vs-tick, unmapped reads=%0d",
             TAG, HARTS, cov_ev[1]);
  endtask

  initial begin
    done = 1'b0; nerr = 0; nopen = 0;
    @(negedge clk);
    do_reset();
    test_reset_defaults();
    test_msip();
    test_mtimecmp();
    test_mtime();
    test_mtip();
    test_unmapped();
    test_reset_mid();
    test_random(3000);
    test_hold_open();
    idle(10);
    report_cov();
    done = 1'b1;
  end

endmodule

